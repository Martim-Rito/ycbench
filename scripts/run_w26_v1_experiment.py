"""First exploratory experiment on Dataset v1: two plain Logistic Regressions, target_top20.

Model A: founder_n_founders, founder_previous_yc, company_one_liner_n_words
Model B: Model A + log1p(attn_google_mentions_pre_raw)

Deliberately minimal: median/mode imputation fitted inside each CV training fold, no scaling, no
balancing, no tuning. Writes reports/w26_v1_experiment_report.md.
"""
import warnings
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.compose import ColumnTransformer
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import average_precision_score, f1_score, precision_score, recall_score, roc_auc_score
from sklearn.model_selection import RepeatedStratifiedKFold
from sklearn.pipeline import Pipeline

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "processed" / "w26_dataset_v1.csv"
REPORT = ROOT / "reports" / "w26_v1_experiment_report.md"

SEED = 0
N_SPLITS, N_REPEATS = 5, 10
K = 20
BASELINE_HITS = 14  # ref_baseline_top20 ∩ target_top20, reproduced in the dataset report (not used for training)

NUMERIC = ["founder_n_founders", "company_one_liner_n_words"]
BINARY = ["founder_previous_yc"]
MODELS = {
    "Model A": NUMERIC + BINARY,
    "Model B": NUMERIC + BINARY + ["attn_log1p"],
}

df = pd.read_csv(DATA)
df = df[df["target_defined"] == 1].sort_values("canonical_slug").reset_index(drop=True)
assert len(df) == 198 and int(df["target_top20"].sum()) == 20
y = df["target_top20"].astype(int).to_numpy()
df["attn_log1p"] = np.log1p(df["attn_google_mentions_pre_raw"])  # the only explicit transformation (0 -> 0)

# ---- missingness among the rows actually used ----
miss_cols = ["founder_n_founders", "founder_previous_yc", "company_one_liner_n_words", "attn_google_mentions_pre_raw"]
miss = df[miss_cols].isna().sum()
miss_rows = df[df[miss_cols].isna().any(axis=1)]


def make_pipeline(cols):
    imp = ColumnTransformer(
        [("num", SimpleImputer(strategy="median"), [c for c in cols if c not in BINARY]),
         ("bin", SimpleImputer(strategy="most_frequent"), [c for c in cols if c in BINARY])]
    )
    return Pipeline([("impute", imp), ("lr", LogisticRegression(random_state=SEED))])


def top_k_hits(p, y, k):
    """Hits in the top k by probability. Ties at the boundary are broken by row order (slug) for the deterministic
    count; the expected count under random tie-breaking is also returned because weak models give many ties."""
    order = np.argsort(-p, kind="stable")
    det = int(y[order[:k]].sum())
    cut = p[order[k - 1]]
    above, tied = p > cut, p == cut
    exp = y[above].sum() + (k - above.sum()) * y[tied].mean()
    return det, float(exp), int(tied.sum()), int(above.sum())


cv = RepeatedStratifiedKFold(n_splits=N_SPLITS, n_repeats=N_REPEATS, random_state=SEED)
splits = list(cv.split(df, y))

results = {}
for name, cols in MODELS.items():
    X = df[cols]
    fold_rows, oof = [], np.zeros((N_REPEATS, len(df)))
    n_conv_warn = 0
    for i, (tr, te) in enumerate(splits):
        pipe = make_pipeline(cols)
        with warnings.catch_warnings(record=True) as w:
            warnings.simplefilter("always")
            pipe.fit(X.iloc[tr], y[tr])
            n_conv_warn += sum("converge" in str(x.message).lower() for x in w)
        p = pipe.predict_proba(X.iloc[te])[:, 1]
        pred = (p >= 0.5).astype(int)
        oof[i // N_SPLITS, te] = p
        fold_rows.append({
            "precision": precision_score(y[te], pred, zero_division=0), "recall": recall_score(y[te], pred, zero_division=0),
            "f1": f1_score(y[te], pred, zero_division=0), "roc_auc": roc_auc_score(y[te], p),
            "pr_auc": average_precision_score(y[te], p), "n_pred_pos": int(pred.sum()),
        })
    folds = pd.DataFrame(fold_rows)
    reps = [top_k_hits(oof[r], y, K) for r in range(N_REPEATS)]
    # coefficients of one fit on all rows, for the report only (no importance analysis)
    full = make_pipeline(cols).fit(X, y)
    results[name] = {
        "cols": cols, "folds": folds, "det": [r[0] for r in reps], "exp": [r[1] for r in reps],
        "ties": [r[2] for r in reps], "above": [r[3] for r in reps], "conv_warn": n_conv_warn,
        "oof_auc": [roc_auc_score(y, oof[r]) for r in range(N_REPEATS)],
        "oof_ap": [average_precision_score(y, oof[r]) for r in range(N_REPEATS)],
        "n_unique_oof": int(len(np.unique(oof[0].round(10)))),
    }


def ms(a):
    a = np.asarray(a, float)
    return f"{a.mean():.3f} ± {a.std(ddof=1):.3f}"


